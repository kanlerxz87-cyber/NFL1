def main():
    ids = [x["id"] for x in ROWS]
    assert len(ids) == len(set(ids)), "duplicate requirement id"
    counts = {}
    for x in ROWS:
        counts[x["status"]] = counts.get(x["status"], 0) + 1
    doc = {
        "meta": {
            "built": "2026-11-15",
            "session": "07810d9f-nfl1",
            "brief": "Requirements of the 2026-11-15 brief (NFL line origination, injuries and depth, leaderboard, site, process)",
            "count": len(ROWS),
            "by_status": counts,
            "legend": {
                "Done": "delivered; the artifact named in evidence exists in the repo",
                "Partial": "some of it exists; the missing part is named",
                "Not started": "no artifact found in the repo",
                "Blocked": "cannot proceed until a named external source or decision exists",
                "Not met": "the repo does the opposite of what the brief requires",
                "Not verified": "not checked in this session; no status is claimed",
                "Rejected (brief)": "the brief rejects it; the note states whether the repo complies",
            },
            "checked_note": "'re-read 2026-11-15' = the source page or file was read again in this session; 'repo artifact, not re-read' = the status rests on the file named in evidence.",
            "source_note": "Each row links the official page it depends on, or the repo file that holds the evidence (internal, not official).",
        },
        "rows": ROWS,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    print(f"wrote {OUT}: {len(ROWS)} rows {counts}")


if __name__ == "__main__":
    main()

METHOD_NOTES = [
    ("Ratings", "Two-way ridge fixed effect on non-garbage-time plays: EPA ~ offence team + defence team + home. Prior season weighted 0.40. Ratings for week W use only weeks before W."),
    ("Own line", "margin = a + b x (net rating difference), fitted on 2024; total fitted on the sum of offence and defence ratings. Both evaluated out of sample in 2025 and 2026."),
    ("Line sign convention", "The mirrored closing line is expressed as points the HOME team is expected to win by, so positive means the home team is favoured. This was measured, not assumed: see the correlation check on the Lines page."),
    ("Strategy gates", "Eight gates: provenance, pre-specified rule, n >= 100, positive recent-window ROI, Benjamini-Hochberg q < 0.10, season stability, drawdown >= -25 units, low correlation with other strategies."),
    ("Luck removal", "Bootstrap distribution of ROI, exact binomial test against the -110 break-even (52.38%), multiple-testing correction across all rules tested, and a lower confidence bound used for ranking."),
    ("Injury and depth", "Official game status joined to the weekly depth chart; starters ranked 1; replacement is the next man at the same slot. Attrition index weights positions and statuses, rescaled 0-100. Explicitly a model assumption."),
    ("Props", "Shrunk player mean, multiplied by a clamped opponent factor; normal interval from the player's own game-level SD. Market price left blank because no official prop source exists."),
]

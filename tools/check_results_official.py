#!/usr/bin/env python3
"""Check the 2026 regular-season results against the official nfl.com week pages.

Inputs (all committed; nothing is fetched by this script)
  data/results/official_read_2026-11-16.tsv        one row per game on
        https://www.nfl.com/schedules/2026/by-week/week-N, read 2026-11-16.
        Column 7 is the exact header text the score was read from.
  data/results/official_records_week10_2026-11-16.tsv   the season record printed next to
        each club on the Week 10 page (read the same day).
  data/verified/games_2026.csv                    the results file the models read.

Outputs (rewritten every run)
  data/results/official_results_2026.csv          one row per official final game, with the
                                                  comparison result and the official link.
  data/results/verification_2026-11-16.json       counts, every mismatch, every gap.

Verification checks (programmatic; a failure makes the script exit 1):
  V1  each header parses to two team nicknames, two scores, a weekday, a month and a day;
  V2  each nickname maps to the club code in the same row;
  V3  the score in the header equals the score columns;
  V4  the URL slug <away>-at-<home>-2026-reg-<week> names the same clubs and the same week;
  V5  the calendar date in the row equals the day printed in the header;
  V6  each official final game matches exactly one games_2026.csv row by (week, away, home)
      and the scores and dates are equal; any difference is listed, never overwritten;
  V7  every games_2026.csv row has an official counterpart (no extra rows);
  V8  for every club, the wins/losses/ties computed from the official scores equal the
      record printed on the Week 10 page.

Coverage (reported, not failed): official final games that are not yet in games_2026.csv.
Each one is listed with its official link so the integration owner can decide to add it.

Run:  python3 tools/check_results_official.py
"""
from __future__ import annotations

import csv
import datetime as dt
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OFFICIAL_TSV = ROOT / "data/results/official_read_2026-11-16.tsv"
RECORDS_TSV = ROOT / "data/results/official_records_week10_2026-11-16.tsv"
CSV_RESULTS = ROOT / "data/verified/games_2026.csv"
OUT_CSV = ROOT / "data/results/official_results_2026.csv"
OUT_JSON = ROOT / "data/results/verification_2026-11-16.json"
OUT_MD = ROOT / "data/results/RESULTS_2026_VERIFIED.md"
READ_DATE = "2026-11-16"

# nfl.com nickname -> club code (the nfl.com code for the Cardinals is AZ; games_2026.csv uses AZ too).
NICK = {
    "Bears": "CHI", "Panthers": "CAR", "Buccaneers": "TB", "Bengals": "CIN",
    "Saints": "NO", "Lions": "DET", "Bills": "BUF", "Texans": "HOU", "Ravens": "BAL",
    "Colts": "IND", "Browns": "CLE", "Jaguars": "JAX", "Falcons": "ATL", "Steelers": "PIT",
    "Jets": "NYJ", "Titans": "TEN", "Cardinals": "AZ", "Chargers": "LAC", "Dolphins": "MIA",
    "Raiders": "LV", "Packers": "GB", "Vikings": "MIN", "Commanders": "WAS", "Eagles": "PHI",
    "Cowboys": "DAL", "Giants": "NYG", "Broncos": "DEN", "Chiefs": "KC", "Seahawks": "SEA",
    "Patriots": "NE", "Rams": "LA", "49ers": "SF",
}

HEADER_RE = re.compile(
    r"^(?P<a>.+?) (?P<as>\d+), (?P<h>.+?) (?P<hs>\d+), FINAL, (?P<dow>\w+), "
    r"(?P<month>\w+) (?P<day>\d+)(st|nd|rd|th)$"
)
SLUG_RE = re.compile(r"/games/(?P<a>[a-z0-9]+(?:-[a-z0-9]+)*?)-at-(?P<h>[a-z0-9]+(?:-[a-z0-9]+)*?)-2026-reg-(?P<wk>\d+)$")
DATE_RE = re.compile(r"^(?P<dow>\w{3}) (?P<iso>\d{4}-\d{2}-\d{2})$")


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def read_tsv(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def write_markdown(finals, scheduled, record_rows, not_in_file, failures) -> None:
    """Human-readable copy of the verified table; every row carries its official link."""
    gap_keys = {(f["week"], f["away"], f["home"]) for f in not_in_file}
    lines = [
        "# 2026 regular-season results: official re-verification",
        "",
        "Generated by `tools/check_results_official.py` from `data/results/official_read_2026-11-16.tsv`",
        "(read from the nfl.com week pages on 2026-11-16 UTC) and compared with `data/verified/games_2026.csv`.",
        "Every row links the official game page it was read from. Blank cells are blank because the source had no value.",
        "",
        f"Official final games read: **{len(finals)}**. Matched exactly to the results file: "
        f"**{sum(1 for f in finals if f.get('csv_match') == 'MATCH')}**. Official finals not yet in the results file "
        f"(coverage gap, flagged): **{len(gap_keys)}**. Verification failures: **{len(failures)}**.",
        "",
        "| Week | Date | Away | Score | Home | Score | In results file | Official game page |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for f in finals:
        status = "yes, matches" if f.get("csv_match") == "MATCH" else "no (gap, flagged)"
        lines.append(
            f"| {f['week']} | {f['gameday']} | {f['away']} | {f['away_score']} | {f['home']} | {f['home_score']} | "
            f"{status} | [{f['official_game_url'].rsplit('/', 1)[-1]}]({f['official_game_url']}) |"
        )
    lines += ["", "## Scheduled, no final score at read time (left blank)", "",
              "| Week | Away | Home | Official game page |", "|---|---|---|---|"]
    for s_ in scheduled:
        lines.append(f"| {s_['week']} | {s_['away']} | {s_['home']} | [{s_['official_game_url'].rsplit('/', 1)[-1]}]({s_['official_game_url']}) |")
    lines += ["", "## Season records: printed on the Week 10 page vs. computed from the official scores", "",
              "| Club | Printed W-L-T | Computed W-L-T | Equal | Source |", "|---|---|---|---|---|"]
    rec_src = {r["club"]: r for r in read_tsv(RECORDS_TSV)}
    for r in record_rows:
        pw = "-".join(str(x) for x in r["printed_w_l_t"])
        cw = "-".join(str(x) for x in r["computed_w_l_t"])
        src = rec_src[r["club"]]["official_url"] if r["club"] in rec_src else ""
        lines.append(f"| {r['club']} | {pw} | {cw} | {'yes' if r['equal'] else 'NO'} | [{src.rsplit('/', 1)[-1]}]({src}) |")
    lines.append("")
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    failures: list[str] = []
    counts = Counter()
    official = read_tsv(OFFICIAL_TSV)
    with CSV_RESULTS.open(newline="", encoding="utf-8") as fh:
        results = list(csv.DictReader(fh))

    finals: list[dict] = []
    scheduled: list[dict] = []
    for r in official:
        wk = int(r["week"])
        if r["away_score"] == "" or r["home_score"] == "":
            scheduled.append({"week": wk, "away": r["away"], "home": r["home"],
                              "official_header_text": r["official_header_text"],
                              "official_game_url": r["official_game_url"],
                              "note": "no final score on the official page at read time; left blank"})
            continue
        header = r["official_header_text"]
        url = r["official_game_url"]
        m = HEADER_RE.match(header)
        counts["V1_header_parses"] += 1
        if not m:
            failures.append(f"V1 header does not parse: {header!r}")
            continue
        a_code, h_code = NICK.get(m["a"]), NICK.get(m["h"])
        counts["V2_nicknames_to_club_codes"] += 1
        if a_code is None or h_code is None:
            failures.append(f"V2 unknown nickname in {header!r}")
            continue
        if (a_code, h_code) != (r["away"], r["home"]):
            failures.append(f"V2 clubs differ: header {m['a']}/{m['h']} -> {a_code}/{h_code}, row {r['away']}/{r['home']}")
        counts["V3_header_scores_equal_columns"] += 1
        if (int(m["as"]), int(m["hs"])) != (int(r["away_score"]), int(r["home_score"])):
            failures.append(f"V3 score differs: header {m['as']}-{m['hs']}, columns {r['away_score']}-{r['home_score']}")
        counts["V4_url_slug"] += 1
        sm = SLUG_RE.search(url)
        if not sm:
            failures.append(f"V4 URL does not match the game-page pattern: {url}")
        else:
            slug_a = m["a"].lower()
            slug_h = m["h"].lower()
            if sm["a"] != slug_a or sm["h"] != slug_h or int(sm["wk"]) != wk:
                failures.append(f"V4 URL {sm['a']}-at-{sm['h']} week {sm['wk']} does not name {m['a']} at {m['h']} in week {wk}")
        dm = DATE_RE.match(r["game_day"])
        counts["V5_date_equals_header_day"] += 1
        if not dm:
            failures.append(f"V5 unparsed date column {r['game_day']!r}")
        else:
            d = dt.date.fromisoformat(dm["iso"])
            if (d.strftime("%A") != m["dow"]) or (d.strftime("%B") != m["month"]) or (d.day != int(m["day"])):
                failures.append(f"V5 date differs: column {r['game_day']} vs header {m['dow']}, {m['month']} {m['day']}")
        finals.append({"season": 2026, "week": wk, "gameday": dm["iso"] if dm else "",
                       "away": r["away"], "away_score": int(r["away_score"]),
                       "home": r["home"], "home_score": int(r["home_score"]),
                       "official_header_text": header, "official_game_url": url, "read_utc": READ_DATE})

    # V6 / V7: compare with the results file.
    index: dict[tuple, list[dict]] = defaultdict(list)
    for o in results:
        index[(int(o["week"]), o["away_abbr"], o["home_abbr"])].append(o)
    official_keys = Counter((f["week"], f["away"], f["home"]) for f in finals)
    for k, v in official_keys.items():
        if v > 1:
            failures.append(f"V6 duplicate official game {k}")

    mismatches: list[dict] = []
    not_in_file: list[dict] = []
    for f in finals:
        key = (f["week"], f["away"], f["home"])
        cands = index.get(key, [])
        counts["V6_lookup"] += 1
        if not cands:
            f["csv_match"] = "NOT_IN_RESULTS_FILE"
            f["csv_game_id"] = ""
            f["csv_away_score"] = f["csv_home_score"] = f["csv_gameday"] = ""
            not_in_file.append(f)
            continue
        if len(cands) > 1:
            failures.append(f"V6 more than one results row for {key}")
            continue
        c = cands[0]
        f["csv_game_id"] = c["game_id"]
        f["csv_away_score"] = c["away_score"]
        f["csv_home_score"] = c["home_score"]
        f["csv_gameday"] = c["gameday"]
        same = (int(c["away_score"]), int(c["home_score"])) == (f["away_score"], f["home_score"]) and c["gameday"] == f["gameday"]
        f["csv_match"] = "MATCH" if same else "MISMATCH"
        if not same:
            mismatches.append({k: f[k] for k in ("week", "away", "away_score", "home", "home_score", "gameday", "official_game_url", "csv_away_score", "csv_home_score", "csv_gameday")})
            failures.append(f"V6 mismatch {key}")
        counts["V6_match" if same else "V6_mismatch"] += 1

    extra = [
        {"game_id": o["game_id"], "week": o["week"], "away": o["away_abbr"], "home": o["home_abbr"]}
        for o in results if (int(o["week"]), o["away_abbr"], o["home_abbr"]) not in official_keys
    ]
    counts["V7_results_rows_checked"] = len(results)
    if extra:
        failures.append(f"V7 {len(extra)} results rows have no official counterpart")

    # V8: records printed on the Week 10 page equal the W-L-T implied by the official scores.
    implied: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0])
    for f in finals:
        a, h, a_s, h_s = f["away"], f["home"], f["away_score"], f["home_score"]
        if a_s > h_s:
            implied[a][0] += 1; implied[h][1] += 1
        elif a_s < h_s:
            implied[h][0] += 1; implied[a][1] += 1
        else:
            implied[a][2] += 1; implied[h][2] += 1
    records = read_tsv(RECORDS_TSV)
    record_rows = []
    for rec in records:
        parts = [int(x) for x in rec["record_as_printed"].split("-")]
        printed = (parts + [0, 0])[:3]
        got = implied[rec["club"]]
        ok = printed == got
        counts["V8_records_checked"] += 1
        if not ok:
            failures.append(f"V8 {rec['club']}: printed {printed} vs computed {got}")
        record_rows.append({"club": rec["club"], "printed_w_l_t": printed, "computed_w_l_t": got, "equal": ok})

    # Write the table: one row per official final game.
    fields = ["season", "week", "gameday", "away", "away_score", "home", "home_score", "csv_match",
              "csv_game_id", "csv_gameday", "csv_away_score", "csv_home_score",
              "official_header_text", "official_game_url", "read_utc"]
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    with OUT_CSV.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        for f in finals:
            w.writerow(f)

    write_markdown(finals, scheduled, record_rows, not_in_file, failures)

    by_week = Counter(f["week"] for f in finals)
    matched = sum(1 for f in finals if f.get("csv_match") == "MATCH")
    report = {
        "generated_by": "tools/check_results_official.py",
        "read_date_utc": READ_DATE,
        "sources": {
            "official_week_pages": [f"https://www.nfl.com/schedules/2026/by-week/week-{w}" for w in range(1, 11)],
            "official_game_pages": "one per row; see official_game_url in data/results/official_results_2026.csv",
        },
        "official_final_games": len(finals),
        "official_final_games_by_week": dict(sorted(by_week.items())),
        "results_file": rel(CSV_RESULTS),
        "results_file_rows": len(results),
        "matched_exactly": matched,
        "mismatches": mismatches,
        "coverage_gap_official_finals_not_in_results_file": [
            {"week": f["week"], "away": f["away"], "home": f["home"], "official_game_url": f["official_game_url"]}
            for f in not_in_file
        ],
        "results_rows_without_official_counterpart": extra,
        "scheduled_not_final_at_read_time": scheduled,
        "record_check": record_rows,
        "checks": dict(counts),
        "failures": failures,
        "verification_pass": not failures,
    }
    OUT_JSON.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")

    print(f"official final games read: {len(finals)}  (scheduled, not final: {len(scheduled)})")
    print(f"matched exactly to games_2026.csv: {matched}  of {len(results)} results rows")
    print(f"mismatches: {len(mismatches)}  results rows without official counterpart: {len(extra)}")
    print(f"coverage gap (official finals not yet in the results file): {len(not_in_file)}")
    print(f"record check (V8): {counts['V8_records_checked']} clubs")
    for x in failures:
        print("FAIL:", x)
    print("VERIFICATION PASS" if not failures else "VERIFICATION FAIL")
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""build_shadow_site.py — the shadow/ sub-site (P6, session 55dc53f4-nfl1).

Writes shadow/index.html, forecast.html, team-view.html, whats-changed.html and prereg.html from the
data files below. Every value shown is read from those files; nothing is typed in or inferred.
Every table row carries an official source link. A blank cell is blank in the data and is shown blank.
The build fails if an internal link points at a missing file.

Inputs:  prereg/shadow-v1.json, data/shadow/registration_ref.json, data/shadow/forecasts_week11_v1.json,
         data/shadow/team_view.json, data/shadow/whats_changed.json
Output:  shadow/*.html

    python3 tools/build_shadow_site.py
"""
from __future__ import annotations

import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "shadow")
REG_COMMIT = "01da763"
GITHUB_BLOB = f"https://github.com/kanlerxz87-cyber/NFL1/blob/{REG_COMMIT}/"

PAGES = [("index.html", "Overview"), ("forecast.html", "Week 11 forecast"),
         ("team-view.html", "Team view"), ("whats-changed.html", "What changed"),
         ("prereg.html", "Pre-registration")]


def load(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        return json.load(fh)


def e(v) -> str:
    return "" if v is None else html.escape(str(v), quote=True)


def link(url: str, text: str | None = None) -> str:
    return f'<a href="{e(url)}">{e(text if text is not None else url)}</a>'


def nav(current: str) -> str:
    items = []
    for href, label in PAGES:
        cls = ' class="here"' if href == current else ""
        items.append(f'<a href="{href}"{cls}>{e(label)}</a>')
    items.append('<a href="../index.html">Landing page</a>')
    return '<nav>' + " | ".join(items) + '</nav>'


CSS = """
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;max-width:1180px;margin:1.2rem auto;padding:0 1rem;color:#1b1f24;line-height:1.45}
nav{margin:.4rem 0 1rem;font-size:.95rem}nav a{margin-right:.2rem}nav a.here{font-weight:700;text-decoration:none}
table{border-collapse:collapse;width:100%;margin:.6rem 0 1.2rem;font-size:.9rem}
th,td{border:1px solid #d0d7de;padding:.3rem .45rem;text-align:left;vertical-align:top}
th{background:#f6f8fa}td.blank{background:#fff8c5}
.note{background:#f6f8fa;border-left:4px solid #0969da;padding:.5rem .8rem;margin:.8rem 0}
.warn{background:#fff8c5;border-left:4px solid #bf8700;padding:.5rem .8rem;margin:.8rem 0}
footer{margin-top:2rem;font-size:.85rem;color:#57606a}
"""


def page(current: str, title: str, body: str) -> str:
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{e(title)} — shadow-v1 (NFL1)</title>
<style>{CSS}</style></head>
<body>
{nav(current)}
<h1>{e(title)}</h1>
{body}
<footer>Generated by tools/build_shadow_site.py from committed data files. Shadow only: no stake, price or parlay. Nothing here is scored yet.</footer>
</body></html>
"""


def table(headers, rows, blank_cols=()):
    out = ["<table><thead><tr>" + "".join(f"<th>{e(h)}</th>" for h in headers) + "</tr></thead><tbody>"]
    for r in rows:
        cells = []
        for i, c in enumerate(r):
            if isinstance(c, tuple) and c and c[0] == "RAW":
                cells.append(f"<td>{c[1]}</td>")
            elif c is None or c == "":
                cells.append('<td class="blank"></td>' if i in blank_cols else "<td></td>")
            else:
                cells.append(f"<td>{e(c)}</td>")
        out.append("<tr>" + "".join(cells) + "</tr>")
    out.append("</tbody></table>")
    return "".join(out)


def signed(n: int) -> str:
    return f"+{n}" if n > 0 else str(n)


def build_index(reg, fc, delta):
    n_games = len(fc["games"])
    body = f"""
<div class="note"><strong>What this is.</strong> shadow-v1 is a singles-only team-strength forecast. It gives a
win probability for each game. It has no price, no stake and no parlay. It is pre-registered: the rule was
committed before any Week 11 result existed (registration {link(GITHUB_BLOB + 'prereg/shadow-v1.md', REG_COMMIT)}).</div>
<h2>Status</h2>
<ul>
<li>Forecast record: {n_games} Week 11 games, committed {e(reg.get('forecast_record_commit_utc', '2026-11-15T12:53:31Z'))} UTC, before the first kickoff
({e(reg['first_kickoff_et'])}). Record: {link('../' + reg['forecast_record'], reg['forecast_record'])}.</li>
<li>Reproduce it: <code>{e(reg['forecast_record_reproduces'])}</code>. The record must match byte for byte.</li>
<li>Scoring: not possible yet. No Week 11 result exists. The scoring rule is in the pre-registration.</li>
<li>Training corpus: {fc['parameters']['training_games']} finals, weeks 1-10 (games complete at registration). {e(reg['corpus_excludes'])}.</li>
</ul>
<h2>Pages</h2>
<ul>
<li>{link('forecast.html', 'Week 11 forecast')}: the 13 forecasts, each with its official game-centre link.</li>
<li>{link('team-view.html', 'Team view')}: per club, from the 15 Nov official injury read. Starters out and replacements are blank: no official source.</li>
<li>{link('whats-changed.html', 'What changed')}: differences only, 13 Nov vs 15 Nov official reads, with unresolved conflicts shown.</li>
<li>{link('prereg.html', 'Pre-registration')}: the parameters and the hashes that bind the record.</li>
</ul>
<div class="warn"><strong>Flagged items.</strong> Open flags for this sub-site are F-5501-01 to F-5501-13 in
{link('../data/flags.json', 'data/flags.json')}. They are published on the Flagged for Review page
({link('../pages/review.html', 'pages/review.html')}). Unverified or flagged items do not block publication.</div>
"""
    return page("index.html", "Shadow baseline (shadow-v1)", body)


def build_forecast(reg, fc):
    rows = []
    for g in fc["games"]:
        v = g["venue"]
        url = v["game_centre_url"]
        fav = g["benchmarks"]["control_favourite_record_pick"]
        rnd = g["benchmarks"]["control_random_pick"]
        rows.append([
            ("RAW", f"{e(g['away'])} at {e(g['home'])} {link(url, 'game centre')}"),
            f"{g['weekday']} {g['gameday']}",
            g["kickoff_et_as_printed"] + " ET",
            ("RAW", link(url, f"{v['stadium_as_printed']}, {v['location_as_printed']}")),
            "yes (no home-field term)" if g["neutral_site"] else "no",
            f"{g['p_home_win']:.3f}",
            f"{g['predicted_margin_home']:+.2f} (home)",
            fav,
            rnd,
        ])
    body = f"""
<div class="warn"><strong>Forecasts only.</strong> No outcome exists, so nothing is scored and no accuracy is claimed.
Forecasts were committed before the first kickoff, as the pre-registration requires.</div>
<p>Model: margin = b × h + (rating home − rating away). b = {fc['parameters']['home_field_term_b']}, sigma = {fc['parameters']['sigma']},
penalty lambda = {fc['parameters']['penalty_lambda']}. Probability = Φ(margin / sigma). Full rule: {link(GITHUB_BLOB + 'prereg/shadow-v1.md', 'prereg/shadow-v1.md')}.</p>
{table(['Game', 'Day', 'Kickoff', 'Venue (official)', 'Neutral site', 'P(home win)', 'Predicted margin', 'Benchmark: favourite by record', 'Benchmark: seeded random pick'], rows)}
<p>Every row links its official game centre (nfl.com). Week 11 kickoffs and venues are in
{link('../data/shadow/week11_venues.csv', 'data/shadow/week11_venues.csv')}, cross-checked to
{link('../data/model/snapshot.json', 'data/model/snapshot.json')}. Fixture context (rest, short week, division) is in
{link('../data/shadow/week11_context.json', 'data/shadow/week11_context.json')}, recorded but not used by the model.</p>
<p>Club code: the Cardinals appear as ARI in the model and AZ on nfl.com (flag CAP-05).</p>
"""
    return page("forecast.html", "Week 11 forecast (record, not a pick)", body)


def build_team_view(tv):
    rows = []
    for c in tv["clubs"]:
        gs = c["game_status_counts"]
        ps = c["practice_status_counts"]
        rows.append([
            c["club"], c["listed_players"], gs["Out"], gs["Doubtful"], gs["Questionable"], gs["(none)"],
            ps["Did Not Participate In Practice"], ps["Limited Participation in Practice"], ps["Full Participation in Practice"],
            None, None, ("RAW", link(c["source_url"], "nfl.com 15 Nov read")),
        ])
    summary = table(["Club", "Listed", "Out", "Doubtful", "Questionable", "No game status", "Did not participate",
                     "Limited", "Full", "Starters out (blank: no official source, F-5501-05)",
                     "Replacements (blank: no official source)", "Source"], rows, blank_cols=(9, 10))
    prows = []
    for c in tv["clubs"]:
        for p in c["players"]:
            prows.append([c["club"], p["player"], p["position"], p["injury"], p["practice_status"], p["game_status"],
                          ("RAW", link(p["source_url"], "nfl.com injury report"))])
    players = table(["Club", "Player", "Pos", "Injury", "Practice status", "Game status", "Source"], prows)
    body = f"""
<div class="note">Level (not delta): one read, {e(tv['read']['captured'])}, {tv['read']['rows']} rows, {tv['read']['clubs']} clubs.
Every player row links the official page. Blank cells are blank on the page.</div>
<div class="warn">{e(tv['not_in_this_view'])} See F-5501-05.</div>
<h2>Per club</h2>
{summary}
<h2>Every listed player</h2>
{players}
"""
    return page("team-view.html", "Team view (15 Nov official read)", body)


def build_changed(dl):
    rows = []
    for x in dl["per_club_differences"]:
        note = x.get("conflict_flag", "")
        rows.append([x["club"], signed(x["rows_difference"]), signed(x["did_not_participate_difference"]),
                     signed(x["limited_difference"]), signed(x["full_difference"]), note,
                     ("RAW", " ".join(link(u, "15 Nov" if "league/2026" in u else "13 Nov") for u in x["sources"]))])
    diff_table = table(["Club", "Listed rows", "Did not participate", "Limited", "Full", "Note", "Sources"], rows)
    nc = "".join(f"<li><strong>{e(x['club'])}</strong>: {e(x['reason'])}</li>" for x in dl["clubs_not_comparable"])
    cf = "".join(f"<li><strong>{e(x['club'])}</strong>: {e(x['conflict'])} {' '.join(link(u) for u in x['sources'])}</li>" for x in dl["conflicts_unresolved"])
    desig_rows = []
    for x in dl["designations"]["rows"]:
        if x["result"] == "changed":
            parts = "; ".join(f"{k.replace('_', ' ')}: {v['13_nov']} → {v['15_nov']}" for k, v in x["differences"].items())
            desig_rows.append([x["club"], x["player"], "changed", parts])
        elif x["result"] == "unchanged":
            desig_rows.append([x["club"], x["player"], "unchanged", ""])
        else:
            desig_rows.append([x["club"], x["player"], x["result"], ""])
    desig = table(["Club", "Player", "Result", "Difference (only fields that changed)"], desig_rows)
    body = f"""
<div class="note"><strong>Differences only.</strong> The levels are on the {link('team-view.html', 'team view')}.
Reads compared: 13 Nov {link('https://www.nfl.com/injuries/', 'nfl.com/injuries')} (counts for 26 clubs and 9 designations) and 15 Nov
{link('https://www.nfl.com/injuries/league/2026/reg10', 'nfl.com/injuries/league/2026/reg10')} (full transcript).</div>
<div class="warn"><strong>Not claimed:</strong> {e(dl['not_claimed'])}</div>
<h2>Club-level differences (where both reads are complete)</h2>
{diff_table}
<p class="note">A club with a row difference in the table is only counted, not explained. The 13 Nov read gives counts, not names.</p>
<h2>Clubs not comparable</h2>
<ul>{nc}</ul>
<h2>Unresolved conflicts (not chosen, not inferred)</h2>
<ul>{cf}</ul>
<h2>Designations: {dl['designations']['changed']} changed of {dl['designations']['compared']} compared</h2>
{desig}
<p>Club codes: the 13 Nov read uses LA for the Rams; the 15 Nov read uses LAR (mapping in the record; flag CAP-05).</p>
"""
    return page("whats-changed.html", "What changed (13 Nov vs 15 Nov, differences only)", body)


def build_prereg(pr, reg):
    rows = [
        ["Model", pr["model"]["type"]],
        ["Equation", pr["model"]["equation"]],
        ["Penalty lambda", f"{pr['model']['penalty_lambda']} (fixed before results; not tuned)"],
        ["Kickoff cutoff (UTC)", pr["kickoff_cutoff_utc"]],
        ["Corpus", f"{pr['corpus']['n_games']} games; sha256 {pr['corpus']['sha256']}"],
        ["Fixtures", f"{pr['fixtures']['n_games']} games; sha256 {pr['fixtures']['sha256']}"],
        ["Code", f"{pr['code_file']}; sha256 {pr['code_sha256']}"],
        ["Benchmarks", "coin (0.5); seeded random (seed " + str(pr['benchmarks']['control_random']['seed']) + "); favourite by record"],
        ["Scoring", "Brier score; skill vs benchmark; game-cluster bootstrap by week (1000 resamples); no claim below 40 graded games"],
        ["Forecast record", f"{e(reg['forecast_record'])} (reproduce with {e(reg['forecast_record_reproduces'])})"],
    ]
    t = table(["Parameter", "Value (from prereg/shadow-v1.json)"], rows)
    body = f"""
<div class="note">Registration commit <code>{REG_COMMIT}</code>:
{link(GITHUB_BLOB + 'prereg/shadow-v1.md', 'prereg/shadow-v1.md')} (rule text) and
{link(GITHUB_BLOB + 'prereg/shadow-v1.json', 'prereg/shadow-v1.json')} (parameters).</div>
{t}
<h2>Gates</h2>
<ul>{''.join(f'<li><strong>{e(k)}</strong>: {e(v)}</li>' for k, v in pr['gates'].items())}</ul>
<h2>Demotion gate (PR-07)</h2>
<p>{e(pr['demotion_gate_pr07']['status'])}</p>
<ul>{''.join(f'<li>{e(x)}</li>' for x in pr['demotion_gate_pr07']['demote_to_paper_if_any'])}</ul>
"""
    return page("prereg.html", "Pre-registration (shadow-v1)", body)


def check_links(pages: dict[str, str]) -> list[str]:
    """Every relative href must name a page built in this run or an existing file in the repository."""
    bad = []
    for name, text in pages.items():
        for href in re.findall(r'href="([^"]+)"', text):
            if href.startswith(("http://", "https://", "#", "mailto:")):
                continue
            if os.path.normpath(href) in pages:
                continue
            target = os.path.normpath(os.path.join(OUT, href))
            if not os.path.exists(target):
                bad.append(f"{name} -> {href}")
    return bad


def main() -> int:
    pr = load("prereg/shadow-v1.json")
    reg = load("data/shadow/registration_ref.json")
    fc = load("data/shadow/forecasts_week11_v1.json")
    tv = load("data/shadow/team_view.json")
    dl = load("data/shadow/whats_changed.json")
    pages = {
        "index.html": build_index(reg, fc, dl),
        "forecast.html": build_forecast(reg, fc),
        "team-view.html": build_team_view(tv),
        "whats-changed.html": build_changed(dl),
        "prereg.html": build_prereg(pr, reg),
    }
    bad = check_links(pages)
    if bad:
        print("FAILED: broken internal links in shadow/:")
        for b in bad:
            print("  " + b)
        return 1
    os.makedirs(OUT, exist_ok=True)
    for name, text in pages.items():
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
            fh.write(text)
    print(f"wrote {len(pages)} pages to shadow/; internal links checked, 0 broken")
    return 0


if __name__ == "__main__":
    sys.exit(main())
